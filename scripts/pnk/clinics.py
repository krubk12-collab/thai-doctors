def rows():
    clinics = [l.split('|', 1)[1] for l in open(os.path.join(HERE, 'clinics.txt'), encoding='utf-8').read().splitlines() if '|' in l]
    used, out = set(), []
    for l in open(os.path.join(HERE, 'list.txt'), encoding='utf-8').read().splitlines():
        n, sp = (l.split('|') + [''])[:2]
        if not n.strip(): continue
        cl = next((c for k, c in SUB if k in sp), GEN)
        used.update(cl)
        out.append(['pnk', n.strip(), 'อายุรกรรม · คลินิกที่น่าจะประจำ: ' + ', '.join(cl),
                    sp.strip() + ' · ⚠️ จับคู่คลินิกตามสาขา ไม่ใช่ตารางจริง (จากเอกสารหลักสูตร รพ.)', ''])
    for c in clinics:
        if c in used or SKIP.search(c): continue
        out.append(['pnk', '🩺 ' + c, c, NOTE, ''])
    return out


