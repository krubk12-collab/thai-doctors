# จัด รพ./คลินิก เป็น 'รัฐ' หรือ 'เอกชน' จากชื่อ + ประเภทเดิม (ใช้ใน build_docs.py)
# ลำดับ: ประเภทเดิมบอกชัด → ชื่อเครือ/รพ.เอกชนที่รู้จัก → มีคำว่า โรงพยาบาล/สถาบัน/มหาวิทยาลัยรัฐ ฯลฯ = รัฐ → ที่เหลือ (คลินิก) = เอกชน
import re
CHAIN = (r'กรุงเทพ(?!มหานคร|ธนบุรี)|bangkok|พญาไท|เปาโล|สมิติเวช|บำรุงราษฎร์|เกษมราษฎร์|วิภาวดี|วิภาราม|นนทเวช|ธนบุรี(?!.*มหาวิทยาลัย)|เวชธานี|'
         r'กรุงไทย|ชลลดา|เมดพาร์ค|ไทยนครินทร์|ปิยะเวท|ยันฮี|บี\.?แคร์|ศิครินทร์|พระราม ?9|เวิลด์เมดิคอล|มิตรประชา|ศรีสวรรค์|แพทย์รังสิต|'
         r'เมโย|วัฒโนสถ|สิริโรจน์|ศิริโรจน์|แมคคอร์มิค|ลานนา|ราชเวช|พิษณุเวช|รวมแพทย์|หัวเฉียว|มิชชั่น|มิชชัน|เซ็?น(ต์)?หลุยส์|บางโพ|บางมด|'
         r'นครธน|วิชัยเวช|ศิริเวช|ปิยะมินทร์|จุฬารัตน์|เอกอุดร|โรงพยาบาลราชธานี|เทพากร|ขอนแก่นราม|เกษมราษฎร์|international|อินเตอร์เนชั่นแนล|'
         r'มหาวิทยาลัย(สยาม|กรุงเทพธนบุรี|รังสิต|เวสเทิร์น|เกริก|ศรีปทุม|หัวเฉียว|อีสเทิร์นเอเชีย|คริสเตียน|พายัพ)')
GOV = (r'โรงพยาบาล|รพ\.|มหาวิทยาลัย|ม\.|คณะ|สถาบัน|ศูนย์การแพทย์|ส่งเสริมสุขภาพ|สถานีอนามัย|สาธารณสุข|อนามัย|เทศบาล|กระทรวง|'
       r'ทหาร|ตำรวจ|ค่าย|กองทัพ|ศิริราช|รามาธิบดี|จุฬาลงกรณ์|วชิระ')
def sector(name, kind):
    if kind.startswith('รัฐ'): return 'รัฐ'
    if kind.startswith('เอกชน'): return 'เอกชน'
    if re.search(r'ทหาร|ตำรวจ|กองทัพ|นพรัตน|ค่าย', name): return 'รัฐ'  # มาก่อนชื่อเครือ (เช่น รพ.ทหารเรือกรุงเทพ)
    if re.search(CHAIN, name, re.I): return 'เอกชน'
    if re.search(GOV, name): return 'รัฐ'
    return 'เอกชน'

